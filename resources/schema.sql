-- =========================================================
-- Persian Language Learning App
-- Complete SQLite Database Schema — Iteration 1
-- Covers: UC-01, UC-02, UC-03, UC-04
-- =========================================================

-- SQLite requires foreign key enforcement to be ON per connection
PRAGMA foreign_keys = ON;

-- =========================================================
-- TABLE 1: chapters
-- UC-01: Manage Chapters and Basic Details
-- SRS Ref: FR-CH-01 to FR-CH-08, BR-01
-- =========================================================
-- Each row represents one lesson/chapter (e.g. درس اول, درس دوم ...).
-- id       : UUID string generated by the application (FR-CH-02)
-- title    : Admin-supplied title; non-blank enforced (BR-01)
-- created_at: Unix epoch timestamp; auto-set on insert
CREATE TABLE IF NOT EXISTS chapters (
    id          TEXT    NOT NULL,
    title       TEXT    NOT NULL CHECK(length(trim(title)) > 0),
    created_at  INTEGER NOT NULL DEFAULT (strftime('%s', 'now')),
    PRIMARY KEY (id)
);

-- Keeps the chapter list ordered oldest-first (FR-CH-03)
CREATE INDEX IF NOT EXISTS idx_chapters_created_at
    ON chapters (created_at ASC);


-- =========================================================
-- TABLE 2: chapter_components
-- UC-02: Configure Chapter Structure
-- SRS Ref: FR-CS-01 to FR-CS-07
-- =========================================================
-- Each row is one instructional block inside a chapter.
-- The 'type' column is one of 7 fixed component kinds defined
-- in ComponentType enum. Admin chooses which types to include
-- and sets their display order via 'sequence'.
--
-- Supported types (matching the textbook image):
--   LEARNING_OBJECTIVES — chapter goals listed at the start
--   DIALOGUE            — مکالمہ  (Persian dialogue with Urdu)
--   READING_PASSAGE     — متن     (main Persian reading text)
--   URDU_EXPLANATION    — توضیح   (Urdu translation / explanation)
--   GRAMMAR_NOTE        — قواعد   (grammar rule explanations)
--   EXAMPLES            — مشق / مثال (practice sentences / examples)
--   GLOSSARY            — مفردات  (chapter word list — see TABLE 4)
--
-- ON DELETE CASCADE: deleting a chapter removes all its components
CREATE TABLE IF NOT EXISTS chapter_components (
    id          TEXT    NOT NULL,
    chapter_id  TEXT    NOT NULL,
    type        TEXT    NOT NULL
                    CHECK(type IN (
                        'LEARNING_OBJECTIVES',
                        'DIALOGUE',
                        'READING_PASSAGE',
                        'URDU_EXPLANATION',
                        'GRAMMAR_NOTE',
                        'EXAMPLES',
                        'GLOSSARY'
                    )),
    sequence    INTEGER NOT NULL DEFAULT 1
                    CHECK(sequence >= 1),
    PRIMARY KEY (id),
    FOREIGN KEY (chapter_id)
        REFERENCES chapters(id)
        ON DELETE CASCADE
);

-- Quickly fetch all components for a chapter in display order (FR-CS-05)
CREATE INDEX IF NOT EXISTS idx_chapter_components_chapter_seq
    ON chapter_components (chapter_id, sequence ASC);


-- =========================================================
-- TABLE 3: component_contents
-- UC-03: Manage Chapter Instructional Content
-- SRS Ref: FR-CS-04 to FR-CS-07
-- =========================================================
-- Stores the actual instructional text for each component block.
-- One component → one content row (1-to-1 relationship).
-- persian_text: RTL Persian/Farsi text entered by the admin
-- urdu_text   : RTL Urdu explanation or translation
-- updated_at  : Unix epoch; auto-set when the row is updated
--
-- ON DELETE CASCADE: deleting a component removes its content
CREATE TABLE IF NOT EXISTS component_contents (
    id           TEXT    NOT NULL,
    component_id TEXT    NOT NULL UNIQUE,
    persian_text TEXT,
    urdu_text    TEXT,
    updated_at   INTEGER NOT NULL DEFAULT (strftime('%s', 'now')),
    PRIMARY KEY (id),
    FOREIGN KEY (component_id)
        REFERENCES chapter_components(id)
        ON DELETE CASCADE
);

-- Look up content by component quickly (FR-CS-04)
CREATE INDEX IF NOT EXISTS idx_component_contents_component_id
    ON component_contents (component_id);


-- =========================================================
-- TABLE 4: glossary_entries
-- UC-04: Manage Chapter Glossary (مفردات)
-- SRS Ref: FR-GL-01 to FR-GL-06, BR-03
-- =========================================================
-- Each row is one vocabulary word for a chapter.
-- A chapter can have many glossary entries (one-to-many).
-- persian_word : The new Persian/Farsi word (non-blank — BR-03)
-- urdu_meaning : The Urdu translation/meaning (non-blank — BR-03)
--
-- ON DELETE CASCADE: deleting a chapter removes all its glossary
--   entries (FR-CH-07, NFR-RL-03)
CREATE TABLE IF NOT EXISTS glossary_entries (
    id           TEXT NOT NULL,
    chapter_id   TEXT NOT NULL,
    persian_word TEXT NOT NULL CHECK(length(trim(persian_word)) > 0),
    urdu_meaning TEXT NOT NULL CHECK(length(trim(urdu_meaning)) > 0),
    PRIMARY KEY (id),
    FOREIGN KEY (chapter_id)
        REFERENCES chapters(id)
        ON DELETE CASCADE
);

-- Fetch all vocabulary for a given chapter (FR-GL-02)
CREATE INDEX IF NOT EXISTS idx_glossary_entries_chapter_id
    ON glossary_entries (chapter_id);
